    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        String customerName = txtCustomerName.getText();

String productName = jComboProduct.getSelectedItem().toString();

double price = Double.parseDouble(txtPrice.getText());

// Calculate VAT
double vat = price * 0.15;

// Calculate Commission
double commission = price * 0.05;

// Calculate Total
double total = price + vat + commission;

// Display results
JOptionPane.showMessageDialog(this,
        "Customer Name: " + customerName
        + "\nProduct: " + productName
        + "\nVAT: R " + vat
        + "\nCOMMISSION: R " + commission
        + "\nTOTAL: R " + total);

// Save information to data.txt
try {
    FileWriter file = new FileWriter("data.txt", true);
    PrintWriter output = new PrintWriter(file);

    output.println("DATA LOG");
    output.println("************************");
    output.println("Customer Name: " + customerName);
    output.println("Product: " + productName);
    output.println("VAT: R " + vat);
    output.println("COMMISSION: R " + commission);
    output.println("TOTAL: R " + total);
    output.println("************************");

    output.close();

    JOptionPane.showMessageDialog(this,
            "Information saved successfully!");

} catch (IOException e) {
    JOptionPane.showMessageDialog(this,
            "Error saving information: " + e.getMessage());
}
    }//GEN-LAST:event_btnProcessActionPerformed

